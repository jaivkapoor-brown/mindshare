import { chromium } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:8788";
const out = process.argv[3] ?? "screenshots";
const browser = await chromium.launch();
const mk = async (w = 360, h = 640) => (await browser.newContext({ viewport: { width: w, height: h }, hasTouch: true, deviceScaleFactor: 2 })).newPage();
const host = await mk();
const phase = (p) => p.evaluate(() => window.__msPhase ?? "");
const until = async (p, ph, ms = 90000) => { const end = Date.now() + ms; while ((await phase(p)) !== ph) { if (Date.now() > end) throw new Error("stuck " + ph); await p.waitForTimeout(150); } };
await host.goto(base + "/"); await host.getByLabel("Your nickname").fill("Host");
await host.getByRole("button", { name: "Play solo with bots" }).click();
await host.locator(".player").nth(3).waitFor();
const code = await host.locator(".bigcode").textContent();
await host.getByRole("radio", { name: "3" }).click();
await host.getByRole("switch", { name: "Insider mode" }).click();
const board = await mk(1280, 720);
await board.goto(`${base}/board/${code}`);
await board.waitForTimeout(800); await board.screenshot({ path: `${out}/20-board-lobby.png` });
await host.getByRole("button", { name: "Start game" }).click();
await until(host, "CLUE"); await host.screenshot({ path: `${out}/21-clue-insider.png`, fullPage: true });
const aud = await mk();
await aud.goto(`${base}/r/${code}?watch=1`);
await aud.getByLabel("Pick a nickname").fill("Watcher"); await aud.getByRole("button", { name: "Join room" }).click();
await host.getByRole("button", { name: "Got it" }).click();
await until(host, "WRITE"); await host.getByLabel("Your answer").fill("a wet dog in a library"); await host.getByRole("button", { name: "Submit" }).click();
await until(host, "MARKET"); await aud.waitForTimeout(1500);
await aud.locator(".vote").first().click(); await aud.locator(".tradebtn.buy").nth(1).click();
await aud.waitForTimeout(500); await aud.screenshot({ path: `${out}/22-audience-market.png`, fullPage: true });
await board.waitForTimeout(32000); await board.screenshot({ path: `${out}/23-board-market.png` });
await until(host, "REVEAL"); await board.waitForTimeout(800); await board.screenshot({ path: `${out}/24-board-reveal.png` });
for (let r = 0; r < 2; r++) {
  await host.getByRole("button", { name: "Scores" }).click(); await host.getByRole("button", { name: "Next round" }).click();
  await until(host, "CLUE"); await host.getByRole("button", { name: "Got it" }).click();
  await until(host, "WRITE"); await host.getByLabel("Your answer").fill("cheese"); await host.getByRole("button", { name: "Submit" }).click();
  await until(host, "REVEAL", 120000);
}
await host.getByRole("button", { name: "Scores" }).click(); await host.getByRole("button", { name: "Final results" }).click();
await until(host, "GAME_OVER"); await host.waitForTimeout(600); await host.screenshot({ path: `${out}/25-gameover-vote.png`, fullPage: true });
await host.locator(".card button.btn").first().click(); await host.waitForTimeout(600);
await host.screenshot({ path: `${out}/26-gameover-results.png`, fullPage: true });
console.log("ok", code);
await browser.close();
