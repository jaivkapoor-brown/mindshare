// Walk a solo game and screenshot every screen at 360x640. Usage: node e2e/shots.mjs [baseUrl] [outDir]
import { chromium } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:8788";
const out = process.argv[3] ?? "screenshots";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 360, height: 640 }, hasTouch: true, deviceScaleFactor: 2 });
const phase = () => page.evaluate(() => window.__msPhase ?? "");
const until = async (p, ms = 90000) => { const end = Date.now() + ms; while ((await phase()) !== p) { if (Date.now() > end) throw new Error("stuck waiting for " + p + " in " + (await phase())); await page.waitForTimeout(150); } };
const shot = async (name, full = true) => { await page.waitForTimeout(400); await page.screenshot({ path: `${out}/${name}.png`, fullPage: full }); console.log("shot", name); };
await page.goto(base + "/");
await page.getByLabel("Your nickname").fill("Jai");
await shot("01-home");
await page.getByRole("button", { name: "Play solo with bots" }).click();
await page.locator(".player").nth(3).waitFor();
await shot("02-lobby");
await page.getByRole("radio", { name: "3" }).click();
await page.getByRole("button", { name: "Start game" }).click();
await until("SETUP", 10000).catch(() => {});
await shot("03-setup", false);
await until("CLUE");
await shot("04-clue");
await page.getByRole("button", { name: "Got it" }).click();
await until("WRITE");
await page.getByLabel("Your answer").fill("a corgi filing its taxes early");
await shot("05-write");
await page.getByRole("button", { name: "Submit" }).click();
await until("MARKET");
await page.locator(".tradebtn.buy").first().click();
await page.waitForTimeout(800);
await shot("06-market", false);
await page.waitForTimeout(31000);
await shot("07-market-tell", false);
await until("VERDICT");
await shot("08-verdict", false);
await until("REVEAL");
await shot("09-reveal");
await page.getByRole("button", { name: "Scores" }).click();
await until("SCOREBOARD");
await shot("10-scoreboard");
await browser.close();
